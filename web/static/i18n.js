// term renders a server-side value for a reader, falling back to the raw value.
export function term(prefix, value, fallback) {
  if (!value) return fallback ?? "";
  const table = TERMS[current] || {};
  return table[`${prefix}.${value}`] ?? fallback ?? value;
}


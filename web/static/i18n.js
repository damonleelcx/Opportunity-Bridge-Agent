let current = "zh-CN";

export function setLocale(l) {
  current = STRINGS[l] ? l : "zh-CN";
  document.documentElement.lang = current;
  for (const el of document.querySelectorAll("[data-i18n]")) {
    el.textContent = t(el.dataset.i18n);
  }
  for (const el of document.querySelectorAll("[data-i18n-ph]")) {
    el.placeholder = t(el.dataset.i18nPh);
  }
  for (const el of document.querySelectorAll("[data-i18n-title]")) {
    el.title = t(el.dataset.i18nTitle);
  }
  // An icon-only control has no text to sweep, so its accessible name has to
  // come from somewhere. Same shape as the two sweeps above rather than a
  // one-off per button.
  for (const el of document.querySelectorAll("[data-i18n-aria]")) {
    el.setAttribute("aria-label", t(el.dataset.i18nAria));
  }
}

export function locale() { return current; }

export function t(key) {
  const table = STRINGS[current] || STRINGS["zh-CN"];
  return table[key] ?? STRINGS["zh-CN"][key] ?? key;
}
